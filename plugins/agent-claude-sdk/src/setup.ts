import type {
  CheckContext,
  CheckItem,
  PluginFactoryContext,
  PluginInstanceConfig,
  SetupContext,
  SetupStep,
} from '@tsugimori/plugin-sdk';

import { agentHome, credentialKey, SetupError } from '@tsugimori/plugin-sdk';
import { mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';

export const apiKeyName = 'ANTHROPIC_API_KEY';
export const oauthTokenName = 'CLAUDE_CODE_OAUTH_TOKEN';
const childKeys = [
  'HOME',
  'PATH',
  'USER',
  'LOGNAME',
  'LANG',
  'LC_ALL',
  'TMPDIR',
  'HTTPS_PROXY',
  'HTTP_PROXY',
  'NO_PROXY',
  'SSL_CERT_FILE',
  'NODE_EXTRA_CA_CERTS',
] as const;

export function claudeEnvironment() {
  return Object.fromEntries(childKeys.map((name) => [name, process.env[name]]));
}

function resolveBundledCli(platform: NodeJS.Platform, arch: string) {
  const requireSdk = createRequire(
    import.meta.resolve('@anthropic-ai/claude-agent-sdk'),
  );
  const target = `${platform}-${arch}`;
  const glibc =
    platform === 'linux' &&
    Boolean(
      (
        process.report.getReport() as {
          header?: { glibcVersionRuntime?: string };
        }
      ).header?.glibcVersionRuntime,
    );
  const targets =
    platform === 'linux' && !glibc ? [target + '-musl', target] : [target];
  for (const candidate of targets) {
    try {
      return requireSdk.resolve(
        `@anthropic-ai/claude-agent-sdk-${candidate}/${platform === 'win32' ? 'claude.exe' : 'claude'}`,
      );
    } catch (error) {
      if (!(
        error instanceof Error &&
        'code' in error &&
        error.code === 'MODULE_NOT_FOUND'
      ))
        throw error;
    }
  }
  throw new SetupError(
    'The platform-specific CLI bundled with the Claude Agent SDK is missing. Reinstall the workspace dependencies.',
  );
}

export function claudeOptions(
  entry: PluginInstanceConfig,
  ctx: PluginFactoryContext,
) {
  const home = entry.options?.claudeHome;
  const tokenEnv = entry.options?.tokenEnv;
  const keyEnv = entry.options?.apiKeyEnv;
  const token =
    typeof tokenEnv === 'string' ? ctx.credential(tokenEnv) : undefined;
  return {
    home: agentHome(
      ctx.workspace,
      entry.id,
      typeof home === 'string' ? home : undefined,
    ),
    token,
    apiKey:
      typeof keyEnv === 'string'
        ? ctx.credential(keyEnv)
        : tokenEnv !== undefined || keyEnv !== undefined
          ? undefined
          : ctx.credential(apiKeyName),
  };
}

async function authStatus(
  ctx: CheckContext,
  options = claudeOptions(ctx.entry, ctx),
  signal?: AbortSignal,
) {
  try {
    const cli = resolveBundledCli(ctx.platform, ctx.arch);
    const result = await ctx.runCommand([cli, 'auth', 'status'], {
      cwd: ctx.workspace,
      signal,
      env: {
        ...claudeEnvironment(),
        CLAUDE_CONFIG_DIR: options.home,
        [apiKeyName]: options.apiKey,
        [oauthTokenName]: options.token,
        DISABLE_AUTOUPDATER: '1',
        CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: '1',
      },
    });
    if (result.exitCode !== 0) return;
    const info: { email?: unknown; loggedIn?: unknown } = JSON.parse(
      result.stdout,
    );
    if (info.loggedIn === true) return info;
  } catch {
    // Authentication state is reported without logging raw CLI output.
  }
}

export async function claudeChecks(ctx: CheckContext): Promise<CheckItem[]> {
  const info = await authStatus(ctx);
  return [
    {
      id: 'claude-login',
      title: 'Claude authentication',
      status: info ? 'ok' : 'fail',
      detail: info
        ? 'Claude reports configured authentication.'
        : 'Claude authentication or the SDK’s bundled CLI is unavailable.',
      fix: info
        ? undefined
        : {
            hint: `Check the Agent SDK install and ask the owner to run /login ${ctx.entry.id}.`,
          },
      capabilities: ['agent'],
    },
  ];
}

async function login(ctx: SetupContext) {
  const method = (
    await ctx.prompt({
      text: 'Reply login to sign in with Claude, or token to use a token generated by claude setup-token.',
    })
  )
    .trim()
    .toLowerCase();
  const options = claudeOptions(ctx.entry, ctx);
  await mkdir(options.home, { recursive: true, mode: 0o700 });
  if (method === 'token') {
    const token = (
      await ctx.prompt({
        secret: true,
        text: 'Run claude setup-token in your own terminal and enter the long-lived token here.',
      })
    ).trim();
    if (!/^sk-ant-oat[0-9A-Za-z_-]{20,}$/.test(token))
      throw new SetupError(
        'Enter the long-lived token generated by claude setup-token.',
      );
    if (
      !(await authStatus(
        ctx,
        { ...options, apiKey: undefined, token },
        ctx.signal,
      ))
    )
      throw new SetupError('Claude did not accept the setup token.');
    const key = credentialKey('CLAUDE_CODE_OAUTH_TOKEN', ctx.entry.id);
    await ctx.writeEnv(key, token);
    ctx.writeConfig({
      entry: {
        options: { ...ctx.entry.options, tokenEnv: key, apiKeyEnv: undefined },
      },
    });
    return;
  }
  if (method !== 'login')
    throw new SetupError('Choose login or token to continue.');
  const cli = resolveBundledCli(ctx.platform, ctx.arch);
  const result = await browserLogin(ctx, cli, options.home);
  const info =
    result?.exitCode === 0
      ? await authStatus(
          ctx,
          { home: options.home, apiKey: undefined, token: undefined },
          ctx.signal,
        )
      : undefined;
  const email = info?.email;
  if (
    typeof email !== 'string' ||
    !/^[^\s@]{1,100}@[A-Za-z0-9.-]{1,100}\.[A-Za-z]{2,24}$/.test(email)
  )
    throw new SetupError(
      'Claude did not report a signed-in account. Retry with login or use a setup token.',
    );
  const answer = await ctx.prompt({
    text: `Claude signed in as ${email}. Reply yes to confirm this account.`,
  });
  if (answer.trim().toLowerCase() !== 'yes')
    throw new SetupError('The Claude account was not confirmed.');
  ctx.writeConfig({
    entry: {
      options: { ...ctx.entry.options, tokenEnv: null, apiKeyEnv: null },
    },
  });
}

async function browserLogin(ctx: SetupContext, cli: string, home: string) {
  let prompted = false;
  let urlShown = false;
  let output = '';
  try {
    return await ctx.runCommand([cli, 'auth', 'login'], {
      cwd: ctx.workspace,
      env: {
        ...claudeEnvironment(),
        CLAUDE_CONFIG_DIR: home,
        NO_COLOR: '1',
        BROWSER: 'false',
      },
      keepInputOpen: true,
      signal: ctx.signal,
      timeoutMs: 10 * 60_000,
      async onChunk(chunk, io) {
        output = (output + chunk).slice(-16_384);
        const line = output.replace(/\x1b\[[0-9;]*m/g, '');
        const candidate =
          /https:\/\/(?:claude\.com\/cai|claude\.ai|platform\.claude\.com|console\.anthropic\.com)\/oauth\/authorize\?[^\s"'<>]+(?=[\s"'<>])/.exec(
            line,
          )?.[0];
        if (
          candidate &&
          !urlShown &&
          !/[?&](?:code|token|access_token|refresh_token)=/i.test(candidate)
        ) {
          urlShown = true;
          await ctx.show(`Open this Claude sign-in link: ${candidate}`);
        }
        if (
          urlShown &&
          !prompted &&
          /paste.*(?:auth|authorization|verification).*code|paste.*code here/i.test(
            line,
          )
        ) {
          prompted = true;
          const code = (
            await ctx.prompt({
              secret: true,
              text: 'Enter the one-time authorization code shown by Claude.',
            })
          ).trim();
          if (!/^[A-Za-z0-9._#-]{8,512}$/.test(code))
            throw new SetupError('Enter the code shown by Claude.');
          io.write(code + '\n');
        }
      },
    });
  } catch (error) {
    if (error instanceof SetupError) throw error;
    throw new SetupError(
      'Claude browser sign-in could not complete. Retry with login or use a setup token.',
    );
  }
}

